// =====================================================================
//  Lightweight in-app localization (EN / DE).
//  - Type-safe: every string is a field on [Strings], so a missing
//    translation is a compile error, not a demo-time crash.
//  - Runtime switch: [LanguageState.current] is Compose state, so flipping
//    the language recomposes the whole app instantly (no Activity restart).
//  - Composables read LocalStrings.current; plain code reads appStrings().
// =====================================================================

enum class AppLanguage(val code: String) { EN("en"), DE("de") }

/** Reactive, persisted app language. Read in composition via LocalStrings. */
object LanguageState {
    var current by mutableStateOf(AppLanguage.EN)
        private set

    /** Restore the saved language (call once after TokenManager.init). */
    fun init() {
        current = if (TokenManager.getLanguage() == AppLanguage.DE.code) AppLanguage.DE else AppLanguage.EN
    }

    fun set(lang: AppLanguage) {
        current = lang
        TokenManager.setLanguage(lang.code)
    }
}

/** The active string table for non-composable code (reference data, services). */
fun appStrings(): Strings = if (LanguageState.current == AppLanguage.DE) DeStrings else EnStrings

/** Provided at the app root; composables read LocalStrings.current. */
val LocalStrings = staticCompositionLocalOf { EnStrings }

